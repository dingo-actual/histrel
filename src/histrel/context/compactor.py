#!/usr/bin/env python3
"""
Context compactor for the benchmark agent.

Compacts the conversation history middle (between protected head and
recent tail) when the estimated input tokens exceed the compaction
threshold. Protected head content (system prompt and original task) is
never compacted.

The compaction summary is generated by an LLM call using a dedicated
compaction system prompt. The summary call's usage is recorded in the
token ledger with call_kind="compaction".

    Important Classes:
        CompactedState: State snapshot after compaction.
        Compactor: Compaction trigger and state creation.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import TYPE_CHECKING

from pydantic import BaseModel

from histrel.core.config import AgentConfig
from histrel.model.messages import (
    Message,
    MessagePart,
    ReasoningPart,
    TextPart,
    ToolRequestPart,
    ToolResultPart,
)
from histrel.model.types import (
    ModelRequest,
    ProviderMessage,
)

if TYPE_CHECKING:
    from histrel.context.token_ledger import TokenLedger
    from histrel.model.adapter_openai_compat import (
        OpenAICompatAdapter,
    )


# Character-to-token heuristic for estimating input size when computing
# the compaction target. Not used for actual token counting.
_CHARS_PER_TOKEN = 4


def estimate_tokens(text: str) -> int:
    """Estimate a text's token count from its length.

    Args:
        text (str): Text to estimate.

    Returns:
        (int) Estimated token count.
    """
    return len(text) // _CHARS_PER_TOKEN


_COMPACTION_SYSTEM_PROMPT = """\
You are a summarization agent creating a context checkpoint for a coding \
agent. Treat the conversation turns below as source material for a compact \
record of prior work.

Produce only the structured summary; do not add a greeting, preamble, or \
prefix. Write the summary in the same language the conversation was using.

NEVER include API keys, tokens, passwords, secrets, credentials, or \
connection strings in the summary — replace any that appear with \
[REDACTED].

## Active Task
State the current objective in one or two sentences.

## Progress
List completed steps, tool calls, and their outcomes. Include file paths \
and line numbers where relevant.

## Key Decisions
List architectural decisions, design choices, and constraints discovered.

## Unresolved Issues
List open bugs, failed tests, and incomplete work. Include error messages.

## Files Changed
List all file paths that were read, modified, or created.

## Remaining Work
List the next steps needed to complete the task.

Target approximately {target_tokens} tokens. Be concise but preserve all factual \
details: file paths, function names, error messages, test names, and \
configuration values. Discard redundant tool outputs and verbose file \
contents."""


class CompactedState(BaseModel):
    """State snapshot after compaction.

    The system_prompt and original_task are protected head content copied
    verbatim — never summarized or dropped. source_message_index_start/end
    cover only the compacted middle, not the protected head.

    Instance Attributes:
        system_prompt (str): System prompt (protected head, verbatim).
        original_task (str): Original task text (protected head, verbatim).
        changed_paths (tuple[str, ...]): Changed file paths.
        diff_summary (str): Summary of changes.
        latest_validation (str): Latest test output.
        unresolved_errors (tuple[str, ...]): Unresolved errors.
        working_summary (str): Durable summary text from the LLM.
        recent_message_ids (tuple[str, ...]): Retained recent message IDs.
        source_message_index_start (int): First compacted index (-1 if no middle).
        source_message_index_end (int): Last compacted index (-1 if no middle).

    The index range is relative to the message list passed to
    ``Compactor.compact``. It equals the journal range as long as that
    list is the journal itself.
    """

    system_prompt: str
    original_task: str
    changed_paths: tuple[str, ...] = ()
    diff_summary: str = ""
    latest_validation: str = ""
    unresolved_errors: tuple[str, ...] = ()
    working_summary: str = ""
    recent_message_ids: tuple[str, ...] = ()
    source_message_index_start: int = -1
    source_message_index_end: int = -1


class Compactor:
    """Compaction trigger and CompactedState creation.

    Instance Attributes:
        _config (AgentConfig): Agent configuration.
        _on_compaction (Callable[[CompactedState], None] | None): Callback
            invoked with every state that compacted a middle, used to
            record the event.
    """

    def __init__(
        self,
        config: AgentConfig,
        on_compaction: Callable[[CompactedState], None] | None = None,
    ) -> None:
        """Initialize the compactor.

        Args:
            config (AgentConfig): Agent configuration.
            on_compaction (Callable[[CompactedState], None] | None):
                Callback invoked with each produced state.
        """
        self._config = config
        self._on_compaction = on_compaction

    def should_compact(
        self,
        estimated_tokens: int,
        usable_context: int,
    ) -> bool:
        """Determine whether compaction should trigger.

        Compaction triggers when estimated tokens are at or above
        compact_at_fraction of usable context.

        Args:
            estimated_tokens (int): Last known input token count.
            usable_context (int): Usable context budget.

        Returns:
            (bool) True if compaction should trigger.
        """
        if usable_context <= 0:
            return False
        threshold = int(usable_context * self._config.compaction.compact_at_fraction)
        return estimated_tokens >= threshold

    def compact(
        self,
        *,
        messages: list[Message],
        system_prompt: str,
        original_task: str,
        recent_tail_count: int,
        model_adapter: OpenAICompatAdapter,
        token_ledger: TokenLedger,
        prior_summary: str = "",
    ) -> CompactedState:
        """Create a CompactedState from the current session state.

        The protected head (system prompt + original task) is copied
        verbatim. The compacted middle covers indices between the head
        and the recent tail. The recent tail is retained. The middle is
        summarized by an LLM call using a dedicated compaction prompt,
        and the usage is recorded in the token ledger with
        call_kind="compaction".

        Args:
            messages (list[Message]): The message view being compacted.
            system_prompt (str): System prompt (protected head).
            original_task (str): Original task text (protected head).
            recent_tail_count (int): Number of messages to retain as tail.
            model_adapter (OpenAICompatAdapter): Model adapter for the summary call.
            token_ledger (TokenLedger): Token ledger for recording the summary call.
            prior_summary (str): Summary of an earlier compaction. It is
                folded into the new summary so earlier work survives a
                second compaction.

        Returns:
            (CompactedState) Compacted state snapshot.
        """
        total = len(messages)
        head_end_index = _find_head_end_index(messages)
        tail_start = max(head_end_index + 1, total - recent_tail_count)
        middle_start, middle_end, has_middle = _middle_range(
            total, head_end_index, recent_tail_count
        )

        # Generate the summary via an LLM call if there is a middle to compact
        working_summary = ""
        if has_middle:
            working_summary = _summarize_middle(
                messages[middle_start : middle_end + 1],
                original_task,
                config=self._config,
                model_adapter=model_adapter,
                token_ledger=token_ledger,
                message_index=middle_start,
                prior_summary=prior_summary,
            )

        state = CompactedState(
            system_prompt=system_prompt,
            original_task=original_task,
            recent_message_ids=tuple(_recent_message_ids(messages, tail_start)),
            source_message_index_start=middle_start,
            source_message_index_end=middle_end,
            working_summary=working_summary,
        )
        if self._on_compaction is not None and has_middle:
            self._on_compaction(state)
        return state


def _find_head_end_index(messages: list[Message]) -> int:
    """Find the index of the first user message (the protected task).

    Args:
        messages (list[Message]): All journal messages.

    Returns:
        (int) Index of the first user message, or 0 if none exists.
    """
    for i, msg in enumerate(messages):
        if msg.role == "user":
            return i
    return 0


def _middle_range(
    total: int,
    head_end_index: int,
    recent_tail_count: int,
) -> tuple[int, int, bool]:
    """Compute the compactable middle range.

    Args:
        total (int): Total number of messages.
        head_end_index (int): Index of the last protected-head message.
        recent_tail_count (int): Number of messages to retain as tail.

    Returns:
        (tuple[int, int, bool]) Inclusive middle start and end indices
        (-1, -1 when there is no middle), and whether a middle exists.
    """
    tail_start = max(head_end_index + 1, total - recent_tail_count)
    middle_start = head_end_index + 1
    middle_end = tail_start - 1
    if middle_start <= middle_end and middle_start < total:
        return middle_start, middle_end, True
    return -1, -1, False


def _recent_message_ids(messages: list[Message], tail_start: int) -> list[str]:
    """Collect the message IDs of the retained recent tail.

    Args:
        messages (list[Message]): All journal messages.
        tail_start (int): Index of the first retained tail message.

    Returns:
        (list[str]) Retained message IDs in order.
    """
    return [str(messages[i].message_id) for i in range(tail_start, len(messages))]


def _summarize_middle(
    middle_messages: list[Message],
    original_task: str,
    *,
    config: AgentConfig,
    model_adapter: OpenAICompatAdapter,
    token_ledger: TokenLedger,
    message_index: int,
    prior_summary: str = "",
) -> str:
    """Summarize the compacted middle with an LLM call.

    Records the summary call's usage in the token ledger with
    call_kind="compaction".

    Args:
        middle_messages (list[Message]): Messages in the compacted middle.
        original_task (str): The original task for context.
        config (AgentConfig): Agent configuration.
        model_adapter (OpenAICompatAdapter): Model adapter for the summary call.
        token_ledger (TokenLedger): Token ledger for recording the summary call.
        message_index (int): Ledger message index for the summary call.
        prior_summary (str): Summary of an earlier compaction to fold in.

    Returns:
        (str) The generated working summary.
    """
    serialized = _serialize_middle_messages(
        middle_messages, original_task, prior_summary
    )
    # Estimate input tokens with a character-based heuristic (tiktoken is
    # not used for production token counting).
    estimated_input_tokens = estimate_tokens(serialized)
    target_tokens = max(
        int(estimated_input_tokens * config.compaction.target_fraction),
        1,
    )
    summary_request = _build_summary_request(serialized, target_tokens, config)
    response = model_adapter.complete(summary_request)
    token_ledger.record(
        message_index=message_index,
        usage=response.usage,
        provider_request_id=response.provider_request_id,
        call_kind="compaction",
    )
    return "".join(response.text_parts)


def _build_summary_request(
    serialized: str,
    target_tokens: int,
    config: AgentConfig,
) -> ModelRequest:
    """Build the compaction summary request.

    Args:
        serialized (str): Serialized middle conversation.
        target_tokens (int): Target summary length in tokens.
        config (AgentConfig): Agent configuration.

    Returns:
        (ModelRequest) The summary request.
    """
    system_prompt_text = _COMPACTION_SYSTEM_PROMPT.format(target_tokens=target_tokens)
    return ModelRequest(
        messages=(
            ProviderMessage(role="system", content=system_prompt_text),
            ProviderMessage(role="user", content=serialized),
        ),
        temperature=config.model_temperature,
        top_p=config.model_top_p,
        reasoning_effort=config.model_reasoning_effort or "max",
        max_tokens_output=target_tokens,
    )


def _format_tool_request(part: ToolRequestPart) -> str:
    """Format a tool request part as one summary line.

    Args:
        part (ToolRequestPart): Tool request part.

    Returns:
        (str) Formatted line.
    """
    args_str = ", ".join(f"{k}={v}" for k, v in (part.arguments or {}).items())
    return f"  [TOOL_CALL] {part.tool_name}({args_str})"


def _format_tool_result(part: ToolResultPart) -> str:
    """Format a tool result part as one summary line.

    Args:
        part (ToolResultPart): Tool result part.

    Returns:
        (str) Formatted line.
    """
    output = part.output or part.error or ""
    if len(output) > 500:
        output = output[:8192] + "...[truncated]"
    if not part.tool_name:
        return f"  [TOOL_RESULT] {output}"
    args_str = ""
    if part.arguments:
        args_str = ", ".join(f"{k}={v}" for k, v in part.arguments.items())
    return f"  [TOOL_RESULT] {part.tool_name}({args_str}): {output}"


def _serialize_middle_messages(
    middle_messages: list[Message],
    original_task: str,
    prior_summary: str = "",
) -> str:
    """Serialize middle messages into a text block for the summarizer.

    Args:
        middle_messages (list[Message]): Messages to summarize.
        original_task (str): The original task for context.
        prior_summary (str): Summary of an earlier compaction to fold in.

    Returns:
        (str) Serialized conversation text.
    """
    lines = [f"Original task: {original_task}", ""]
    if prior_summary:
        lines += [
            "Summary of earlier work, already compacted:",
            prior_summary,
            "",
        ]
    lines.append("Conversation to summarize:")
    for msg in middle_messages:
        text = _extract_text(msg.content)
        if text:
            lines.append(f"[{msg.role.upper()}] {text}")
        for part in msg.content:
            if isinstance(part, ToolRequestPart):
                lines.append(_format_tool_request(part))
            elif isinstance(part, ToolResultPart):
                lines.append(_format_tool_result(part))
    return "\n".join(lines)


def _extract_text(parts: list[MessagePart]) -> str:
    """Extract text content from message parts.

    Args:
        parts (list[MessagePart]): Message content parts.

    Returns:
        (str) Concatenated text from text and reasoning parts.
    """
    texts: list[str] = []
    for part in parts:
        if isinstance(part, (TextPart, ReasoningPart)):
            texts.append(part.text)
    return "\n".join(texts)
